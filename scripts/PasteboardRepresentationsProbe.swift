import Foundation

@main struct PasteboardRepresentationsProbe {
    static func main() {
        typealias Policy = PublicPasteboardRepresentations
        let tiff: Set<String> = ["public.tiff", "NeXT TIFF v4.0 pasteboard type"]
        let png: Set<String> = ["public.png", "Apple PNG pasteboard type"]
        let jpeg: Set<String> = ["public.jpeg", "CorePasteboardFlavorType 0x4A504547"]
        for image in [tiff, png, jpeg, tiff.union(png), tiff.union(jpeg)] {
            precondition(Policy.isImageOnly(image))
            precondition(Policy.isImageOnly(image.union([Policy.sourceType])))
            for other in ["public.html", "public.rtf", "public.file-url", "com.apple.webarchive", "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", Policy.optimizedImageMarker] {
                precondition(!Policy.isImageOnly(image.union([other])), "Mixed or private content must not be rewritten: \(other)")
            }
        }
        precondition(Policy.imageFormat(in: tiff.union(jpeg)) == .jpeg)
        precondition(Policy.imageFormat(in: tiff.union(png)) == .png)
        precondition(!Policy.isImageOnly([]))
        precondition(!Policy.isImageOnly([Policy.sourceType]))
        for url in [["public.url", "Apple URL pasteboard type"], ["public.utf8-plain-text", "NSStringPboardType"], ["public.utf16-external-plain-text"]] {
            let types = Set(url)
            precondition(Policy.isTextURLOnly(types))
            precondition(Policy.isTextURLOnly(types.union([Policy.sourceType, "public.url-name", "CorePasteboardFlavorType 0x75726C6E", "Apple URL name pasteboard type"])))
            for other in ["public.png", "public.rtf", "NeXT RTFD pasteboard type", "public.file-url", "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType"] {
                precondition(!Policy.isTextURLOnly(types.union([other])))
            }
        }
        let nativeURL: Set<String> = ["public.url", "CorePasteboardFlavorType 0x75726C20", "dyn.ah62d4rv4gu8yc6durvwwaznwmuuha2pxsvw0e55bsmwca7d3sbwu", "Apple URL pasteboard type", "public.url-name", "CorePasteboardFlavorType 0x75726C6E"]
        precondition(Policy.isTextURLOnly(nativeURL))
        precondition(!Policy.isTextURLOnly(nativeURL.union(["dyn.unknown-rich-content"])))
        precondition(!Policy.isTextURLOnly([Policy.sourceType, "public.url-name"]))
        precondition(Policy.hasURL(in: ["Apple URL pasteboard type"]))
        precondition(!Policy.hasURL(in: ["public.utf8-plain-text"]))
        print("Pasteboard aliases accepted; compressed images preferred; mixed, private and self-generated payloads rejected")
    }
}
