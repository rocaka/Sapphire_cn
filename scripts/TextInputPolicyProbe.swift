import Foundation

@main struct TextInputPolicyProbe {
    static func main() throws {
        var matcher = PublicSnippetMatcher()
        matcher.configure([.init(trigger: "brb", replacement: "Be right back"), .init(trigger: ";签", replacement: "签名👩🏽‍💻")])
        for letter in "brb" { precondition(matcher.feed(String(letter), source: "a", afterDelimiter: true) == nil) }
        precondition(matcher.feed(" ", source: "a", afterDelimiter: true) == .init(typedSuffix: "brb ", template: "Be right back ", requiresWordBoundary: true))
        for letter in "unbrb" { precondition(matcher.feed(String(letter), source: "a", afterDelimiter: false) == nil) }
        matcher.reset()
        precondition(matcher.feed(";", source: "a", afterDelimiter: false) == nil)
        precondition(matcher.feed("签", source: "a", afterDelimiter: false)?.template == "签名👩🏽‍💻")
        precondition(matcher.feed("br", source: "a", afterDelimiter: false) == nil)
        precondition(matcher.feed("b", source: "other-app", afterDelimiter: false) == nil, "An app change must discard the old trigger prefix")
        matcher.reset()
        _ = matcher.feed("br", source: "a", afterDelimiter: false)
        matcher.backspace()
        precondition(matcher.feed("b", source: "a", afterDelimiter: false) == nil)
        matcher.configure([.init(trigger: "é", replacement: "accent"), .init(trigger: "👩🏽‍💻", replacement: "unicode")])
        let composed = matcher.feed("e\u{301}", source: "a", afterDelimiter: false)!
        precondition(composed.typedSuffix.utf16.count == 2, "The edit must delete the actual UTF-16 suffix, not the normalized rule length")
        precondition(matcher.feed("👩🏽‍💻", source: "a", afterDelimiter: false)?.template == "unicode")
        matcher.configure([.init(trigger: String(repeating: "a", count: 129), replacement: "invalid"), .init(trigger: "ok", replacement: "valid")])
        precondition(matcher.rules.count == 1)
        for _ in 0..<10_000 { _ = matcher.feed("a", source: "a", afterDelimiter: false) }
        precondition(matcher.buffer.count <= 4 && matcher.buffer.utf16.count <= 2_048)
        _ = matcher.feed("\n", source: "a", afterDelimiter: false)
        precondition(matcher.buffer.isEmpty, "Navigation/control characters invalidate the suffix")
        precondition(PublicSnippetMatcher.isWordBoundary(preceding: "") && PublicSnippetMatcher.isWordBoundary(preceding: " "))
        precondition(!PublicSnippetMatcher.isWordBoundary(preceding: "un") && !PublicSnippetMatcher.isWordBoundary(preceding: "_"))
        precondition(!PublicSnippetMatcher.isWordBoundary(preceding: "e\u{301}") && !PublicSnippetMatcher.isWordBoundary(preceding: nil), "Existing text and unreadable context must not bypass the word boundary")

        var clipboardReads = 0
        let date = Date(timeIntervalSince1970: 1_700_000_000)
        let plain = try PublicSnippetTemplate.render("plain {{unknown}}", now: date) { clipboardReads += 1; return "secret" }
        precondition(plain == "plain {{unknown}}" && clipboardReads == 0)
        let rendered = try PublicSnippetTemplate.render("{{clipboard}} / {{clipboard}} / {{date:yyyy}} / {{time}}", now: date) { clipboardReads += 1; return "$1\\literal" }
        precondition(rendered.hasPrefix("$1\\literal / $1\\literal / ") && clipboardReads == 1, "Clipboard replacement is literal and read at most once")
        precondition(!rendered.contains("{{date") && !rendered.contains("{{time}}"))
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            precondition(!PublicSnippetTemplate.permitsClipboardTypes(["public.utf8-plain-text", marker]))
        }
        do { _ = try PublicSnippetTemplate.render("{{clipboard}}", now: date) { nil }; preconditionFailure("Private/unavailable clipboard must not expand") }
        catch PublicSnippetTemplate.Failure.clipboardUnavailable { }
        do { _ = try PublicSnippetTemplate.render("{{clipboard}}", now: date) { String(repeating: "x", count: 32_769) }; preconditionFailure("Expansion must be bounded") }
        catch PublicSnippetTemplate.Failure.outputTooLarge { }

        let a = "file:///tmp/a.txt", b = "file:///tmp/b.txt"
        precondition(PublicFinderCutPolicy.acceptsTarget(enabled: true, finderPID: 10, focusedPID: 10, eventTargetPID: 10))
        precondition(!PublicFinderCutPolicy.acceptsTarget(enabled: true, finderPID: 10, focusedPID: 11, eventTargetPID: 0), "A delayed activation notification must not remap keys in another app")
        precondition(!PublicFinderCutPolicy.acceptsTarget(enabled: true, finderPID: 10, focusedPID: 10, eventTargetPID: 11))
        precondition(!PublicFinderCutPolicy.acceptsTarget(enabled: false, finderPID: 10, focusedPID: 10, eventTargetPID: 10))
        var cut = PublicFinderCutPolicy()
        cut.beginCopy(changeCount: 1, files: [a, b])
        precondition(!cut.confirmCopy(current: .init(changeCount: 1, files: [a, b])), "Old clipboard content must not arm a move")
        precondition(cut.confirmCopy(current: .init(changeCount: 2, files: [b, a])))
        precondition(cut.consume(current: .init(changeCount: 2, files: [a, b]), finderActive: true))
        precondition(!cut.consume(current: .init(changeCount: 2, files: [a, b]), finderActive: true), "Each cut is consumed exactly once")
        cut.beginCopy(changeCount: 2, files: [a])
        precondition(!cut.confirmCopy(current: .init(changeCount: 3, files: [b])), "A background copy of other files cannot be mistaken for Finder's Copy")
        precondition(!cut.consume(current: .init(changeCount: 3, files: [b]), finderActive: true))
        cut.beginCopy(changeCount: 3, files: [a])
        precondition(!cut.confirmCopy(current: nil, observedChangeCount: 4))
        precondition(!cut.confirmCopy(current: .init(changeCount: 5, files: [a])), "An intervening text copy must invalidate an unconfirmed cut too")
        cut.beginCopy(changeCount: 3, files: [a]); precondition(cut.confirmCopy(current: .init(changeCount: 4, files: [a])))
        precondition(!cut.consume(current: .init(changeCount: 5, files: [a]), finderActive: true), "Copying even the same path creates a different file version")
        cut.beginCopy(changeCount: 5, files: [a]); precondition(cut.confirmCopy(current: .init(changeCount: 6, files: [a])))
        precondition(!cut.consume(current: .init(changeCount: 6, files: [a]), finderActive: false))
        cut.beginCopy(changeCount: 6, files: [a]); precondition(cut.confirmCopy(current: .init(changeCount: 7, files: [a])))
        cut.reset()
        precondition(!cut.consume(current: .init(changeCount: 7, files: [a]), finderActive: true), "Sleep, permission, focus and settings changes clear cut state")
        precondition(PublicFinderClipboardVersion(changeCount: 8, files: ["https://example.com"]) == nil)
        print("Public text input: trigger boundaries, Unicode edits, bounded suffixes, template privacy, exact Finder copy identity and cut invalidation passed")
    }
}
